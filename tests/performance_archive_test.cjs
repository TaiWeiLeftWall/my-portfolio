const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const context = { console, URLSearchParams, document: {addEventListener() {}}, window: {addEventListener() {}} };
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(root, 'data.js'), 'utf8'), context);
vm.runInContext(fs.readFileSync(path.join(root, 'performance-media.js'), 'utf8'), context);
vm.runInContext(fs.readFileSync(path.join(root, 'script.js'), 'utf8'), context);
const check = code => vm.runInContext(code, context);
assert.equal(check('typeof PERFORMANCE_ARCHIVE_MEDIA'), 'object');
assert.equal(check('Object.keys(PERFORMANCE_ARCHIVE_MEDIA).length'), 2888);
assert.equal(check('Object.keys(PERFORMANCE_GENRES).length'), 2);
assert.equal(check('Object.values(PERFORMANCE_GENRES).reduce((n,g)=>n+Object.keys(g.series).length,0)'), 7);
assert.equal(check("performanceGenre({collection:'performance-gr'})"), 'rock');
assert.equal(check("performanceGenre({collection:'performance-welcome'})"), 'campus');
assert.equal(check("isPerformanceArchive({images:[{src:'images/performance-archive/001/001.webp'}]})"), true);
assert.equal(check("isPerformanceArchive({images:[{src:'https://example.com/old.jpg'}]})"), false);
check("PERFORMANCE_ARCHIVE_MEDIA['https://example.com/archive'] = 'images/performance-archive/thumbs/test.webp'");
assert.equal(check("isPerformanceArchive({images:[{src:'https://example.com/archive'}]})"), true);
assert.equal(check("performanceThumbnail('https://example.com/archive')"), 'images/performance-archive/thumbs/test.webp');
assert.equal(check("performanceThumbnail('https://example.com/old.jpg')"), '');
assert.equal(check("slideCount({category:'performance',images:[1,2]})"), 2);
assert.equal(check("slideCount({category:'portrait',images:[1,2]})"), 3);
console.log('PASS performance taxonomy, archive scope and photo-first slide counts');
